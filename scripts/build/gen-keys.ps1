<#
.SYNOPSIS
  Generates src/Zinc.Core/Ghostty/GhosttyKey.g.cs from libghostty-vt's key header.

.DESCRIPTION
  Reads the GhosttyKey enum from native/include/ghostty/vt/key/event.h (libghostty.ps1 puts it there) and writes one
  C# member per key, numbered in order. Rerun it after bumping the Ghostty commit, because AbiTests fails when the file
  is out of date.

.EXAMPLE
  pwsh scripts/build/gen-keys.ps1
#>
#Requires -Version 7.4
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)

$header = [IO.File]::ReadAllText((Join-Path $root 'native\include\ghostty\vt\key\event.h'))
$header = [regex]::Replace($header, '/\*.*?\*/', '', 'Singleline')
$header = [regex]::Replace($header, '//.*', '')
$body = [regex]::Match($header, '\{([^{}]*)\}\s*GhosttyKey;')
if (-not $body.Success) { throw 'No GhosttyKey enum in event.h.' }

$names = $body.Groups[1].Value -split ',' |
    ForEach-Object { ($_ -split '=')[0].Trim() } |
    Where-Object { $_ -and $_ -ne 'GHOSTTY_KEY_MAX_VALUE' }

# GHOSTTY_KEY_ARROW_LEFT -> ArrowLeft
function Pascal([string]$name) {
    -join ($name.Substring('GHOSTTY_KEY_'.Length) -split '_' | Where-Object { $_ } |
        ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1).ToLowerInvariant() })
}

$lines = @(
    '// <auto-generated> from native/include/ghostty/vt/key/event.h by scripts/build/gen-keys.ps1 </auto-generated>'
    'namespace Zinc.Ghostty;'
    ''
    '/// <summary>Physical key codes (W3C UI Events KeyboardEvent.code); mirrors GhosttyKey.</summary>'
    'public enum GhosttyKey'
    '{'
)
for ($i = 0; $i -lt $names.Count; $i++) { $lines += "    $(Pascal $names[$i]) = $i," }
$lines += '}'

$out = Join-Path $root 'src\Zinc.Core\Ghostty\GhosttyKey.g.cs'
[IO.File]::WriteAllText($out, ($lines -join "`n") + "`n")
Write-Host "$($names.Count) keys"
