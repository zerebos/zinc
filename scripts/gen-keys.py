"""Generates src/Zinc.Core/Ghostty/GhosttyKey.g.cs from the libghostty-vt key header."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "native/include/ghostty/vt/key/event.h").read_text()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//.*", "", src)
body = re.search(r"\{([^{}]*)\}\s*GhosttyKey;", src).group(1)
names = [n.split("=")[0].strip() for n in body.split(",") if n.strip()]
names = [n for n in names if n != "GHOSTTY_KEY_MAX_VALUE"]

def pascal(n):
    return "".join(p.capitalize() for p in n[len("GHOSTTY_KEY_"):].split("_"))

out = [
    "// <auto-generated> from native/include/ghostty/vt/key/event.h by scripts/gen-keys.py </auto-generated>",
    "namespace Zinc.Ghostty;",
    "",
    "/// <summary>Physical key codes (W3C UI Events KeyboardEvent.code); mirrors GhosttyKey.</summary>",
    "public enum GhosttyKey",
    "{",
]
out += [f"    {pascal(n)} = {i}," for i, n in enumerate(names)]
out.append("}")
(root / "src/Zinc.Core/Ghostty/GhosttyKey.g.cs").write_text("\n".join(out) + "\n", newline="\n")
print(f"{len(names)} keys")
